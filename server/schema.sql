CREATE TABLE IF NOT EXISTS empleados (
  no       text PRIMARY KEY,
  name     text NOT NULL,
  role     text NOT NULL CHECK (role IN ('tec', 'jr', 'full', 'sr', 'gte')),
  dept     text NOT NULL,
  boss     text REFERENCES empleados (no),
  shift    text NOT NULL CHECK (shift IN ('A', 'B', 'C')),
  area     text NOT NULL,
  email    text NOT NULL UNIQUE,
  -- shortcut: contraseña en texto plano, guardar un hash al agregar seguridad
  password text NOT NULL
);

CREATE TABLE IF NOT EXISTS actividades (
  id       integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  assignee text NOT NULL REFERENCES empleados (no),
  assigner text NOT NULL REFERENCES empleados (no),
  date     date NOT NULL,
  shift    text NOT NULL CHECK (shift IN ('A', 'B', 'C')),
  time     time NOT NULL,
  text     text NOT NULL,
  status   text NOT NULL CHECK (status IN ('done', 'progress', 'pending', 'incomplete')),
  pct      integer NOT NULL CHECK (pct BETWEEN 0 AND 100)
);

CREATE TABLE IF NOT EXISTS notificaciones (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recipient   text NOT NULL REFERENCES empleados (no),
  kind        text NOT NULL,
  actor       text NOT NULL REFERENCES empleados (no),
  activity_id integer REFERENCES actividades (id),
  count       integer,
  time        time NOT NULL,
  read        boolean NOT NULL DEFAULT false
);
